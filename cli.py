def handle_option(enabled_arg: str, args: argparse.Namespace) -> None:
    if enabled_arg == 'sync':
        try:
            chain : ChainID     = string_to_chain(args.sync[0].lower())
            symbol: Symbol      = Symbol(args.sync[1].lower())
            unit  : TornadoUnit = TornadoUnit(args.sync[2])
        except ValueError as e:
            log.error(tag, f'Invalid arguments for --sync: {args.sync}, exception: {e}')
            return
        try:
            keep: bool | None = False if args.keep is None else bool(args.keep)
        except ValueError as e:
            log.error(tag, f'Invalid arguments for --keep: {args.keep}, exception: {e}')
            return
        meta: Metadata = helper_func.load_metadata().get(chain)
        if meta is None:
            log.error(tag, f'Unsupported chain: {chain_to_string(chain)}')
            return
        elif symbol not in meta.deployment:
            log.error(tag, f'Unsupported symbol: {symbol.value} on chain: {chain_to_string(chain)}')
            return
        elif unit not in meta.deployment[symbol]:
            log.error(tag, f'Unsupported unit: {unit.value} for symbol: {symbol.value} on chain: {chain_to_string(chain)}')
            return
        sync_events(chain, symbol, unit, keep)
    elif enabled_arg == 'sync_all':
        try:
            keep: bool | None = False if args.keep is None else bool(args.keep)
        except ValueError as e:
            log.error(tag, f'Invalid arguments for --keep: {args.keep}, exception: {e}')
            return
        sync_all_events(keep)
    elif enabled_arg == 'deposit':
        try:
            key   : Key         = Key(args.deposit[0])
            chain : ChainID     = string_to_chain(args.deposit[1].lower())
            symbol: Symbol      = Symbol(args.deposit[2].lower())
            unit  : TornadoUnit = TornadoUnit(args.deposit[3])
        except ValueError as e:
            log.error(tag, f'Invalid arguments for --deposit: {args.deposit}, exception: {e}')
            return
        deposit(key, chain, symbol, unit)
    elif enabled_arg == 'deposit_batch':
        try:
            key  : Key = Key(args.deposit_batch[0])
            batch: str = str(args.deposit_batch[1]).lower()
        except ValueError as e:
            log.error(tag, f'Invalid arguments for --deposit_batch: {args.deposit_batch}, exception: {e}')
            return
        deposit_batch(key, batch)
    elif enabled_arg == 'deposit_invoice':
        try:
            key    : Key = Key(args.deposit_invoice[0])
            invoice: str = str(args.deposit_invoice[1]).lower()
        except ValueError as e:
            log.error(tag, f'Invalid arguments for --deposit_invoice: {args.deposit_invoice}, exception: {e}')
            return
        parsed: tuple[ChainID, Symbol, TornadoUnit, HexBytes] | None = Note.from_invoice(invoice)
        if parsed is None:
            log.error(tag, f'Invalid invoice: {invoice}')
            return
        deposit(key, *parsed)
    elif enabled_arg == 'withdraw':
        try:
            note_text: str             = str(args.withdraw[0])
            recipient: ChecksumAddress = Web3.to_checksum_address(args.withdraw[1])
            fee_payer: str             = str(args.withdraw[2])
        except ValueError as e:
            log.error(tag, f'Invalid arguments for --withdraw: {args.withdraw}, exception: {e}')
            return
        key    : Key | None = None
        relayer: str        = fee_payer
        try:
            key = Key(fee_payer)
        except:
            pass
        if key is not None:
            withdraw(note_text, recipient, key)
        else:
            withdraw(note_text, recipient, relayer)
    elif enabled_arg == 'withdraw_batch':
        try:
            note_text: str             = str(args.withdraw_batch[0])
            recipient: ChecksumAddress = Web3.to_checksum_address(args.withdraw_batch[1])
            fee_payer: str             = str(args.withdraw_batch[2])
        except ValueError as e:
            log.error(tag, f'Invalid arguments for --withdraw_batch: {args.withdraw_batch}, exception: {e}')
            return
        key    : Key | None = None
        relayer: str        = fee_payer
        try:
            key = Key(fee_payer)
        except:
            pass
        if key is not None:
            withdraw_batch(note_text, recipient, key)
        else:
            withdraw_batch(note_text, recipient, relayer)
    elif enabled_arg == 'create_note':
        try:
            chain : ChainID     = string_to_chain(args.create_note[0].lower())
            symbol: Symbol      = Symbol(args.create_note[1].lower())
            unit  : TornadoUnit = TornadoUnit(args.create_note[2])
        except ValueError as e:
            log.error(tag, f'Invalid arguments for --create_note: {args.create_note}, exception: {e}')
            return
        create_note(chain, symbol, unit)
    elif enabled_arg == 'note_deposited':
        note_deposited(str(args.note_deposited))
    elif enabled_arg == 'note_withdrawn':
        note_withdrawn(str(args.note_withdrawn))
    elif enabled_arg == 'note_detail':
        parsed: tuple[ChainID, Symbol, TornadoUnit, Note] | None = Note.from_text(str(args.note_detail))
        if parsed is None:
            log.error(tag, f'Failed to parse note: "{args.note_detail}"')
            return
        chain, symbol, unit, note = parsed
        log.info(tag, f'Note detail:\n'
                      f'  Invoice       : {Note.to_invoice(chain, symbol, unit, note)}\n'
                      f'  Chain         : {helper_func.upper_first_char(chain_to_string(chain))}({hex(chain.value)})\n'
                      f'  Symbol        : {symbol.value.upper()}\n'
                      f'  Unit          : {unit.value}\n'
                      f'  Nullifier     : 0x{note.nullifier.hex().zfill(62)}\n'
                      f'  Secret        : 0x{note.secret.hex().zfill(62)}\n'
                      f'  Nullifier Hash: 0x{note.nullifier_hash.hex().zfill(64)}\n'
                      f'  Commitment    : 0x{note.commitment.hex().zfill(64)}')
    elif enabled_arg == 'note_age':
        note_age(str(args.note_age))


class _SyncProgress(Tornado.Handler):

    def __init__(self, tornado: Tornado) -> None:
        self.label       : str = f'{helper_func.upper_first_char(chain_to_string(tornado.chain))}@{tornado.unit.value}{tornado.symbol.value.upper()}'
        self.latest_block: int = 0

    def on_first_catchup(self, _chain: ChainID, _symbol: Symbol, _unit: TornadoUnit) -> None:
        log.info(tag, f'{self.label}, catch up to the latest blockchain')

    def on_sync(self, block_from: int, block_to: int, deposits: list[EventDeposit], withdrawals: list[EventWithdraw]) -> None:
        progress: float = min(100.0, 100.0 * block_to / max(1, self.latest_block))
        log.info(tag, f'{self.label}, synced {block_to - block_from + 1} blocks from {block_from} to {block_to}, '
                      f'progress: {progress:.2f}%, deposits: {len(deposits)}, withdrawals: {len(withdrawals)}')

    def on_latest_block(self, block_number: int) -> None:
        self.latest_block = block_number


@contextmanager
def _running_sync(pools: list[Tornado]) -> Iterator[Callable[[Tornado], bool] | None]:
    """Register every pool before releasing the first RPC query."""
    start_gate: threading.Event = threading.Event()
    running   : list[Tornado]   = []

    def finish(tornado: Tornado) -> bool:
        if not tornado.poller.wait_sync():
            log.error(tag, 'Synchronization stopped before catch-up.')
            return False
        tornado.stop_sync()
        tornado.remove_all_handlers()
        running.remove(tornado)
        return True

    try:
        for tornado in pools:
            if not tornado.start_sync(start_gate=start_gate):
                log.error(tag, 'Could not start pool synchronization.')
                yield None
                return
            running.append(tornado)
            tornado.add_handler(_SyncProgress(tornado))
        start_gate.set()
        yield finish
    finally:
        start_gate.set()
        for tornado in running:
            tornado.stop_sync()
            tornado.remove_all_handlers()


def _sync_pools(pools: list[Tornado], keep: bool = False) -> bool:
    if not pools:
        return True
    with _running_sync(pools) as finish:
        if finish is None:
            return False
        if not keep:
            return all(finish(tornado) for tornado in pools)
        while any(tornado.poller.is_started() for tornado in pools):
            sleep(0.5)
        log.error(tag, 'Pool synchronization stopped.')
        return False


def sync_events(chain: ChainID, symbol: Symbol, unit: TornadoUnit, keep: bool) -> None:
    tornado: Tornado = Tornado(chain, symbol, unit)
    if not tornado.init(sync_only=True):
        return
    try:
        _sync_pools([tornado], keep)
    except KeyboardInterrupt:
        log.warn(tag, 'Interrupted')
    finally:
        tornado.un_init()


def sync_all_events(keep: bool) -> None:
    connections: dict[ChainID, rpc.Interface] = {}
    instances  : list[Tornado]                = []
    try:
        for chain, metadata in helper_func.load_metadata().items():
            connection: rpc.Interface = rpc.Connection(chain, config.RPC_URLS[chain])
            connections[chain] = connection
            if not connection.start():
                log.error(tag, f'Failed to connect to RPC for {chain_to_string(chain)}')
                return
            reader: ChainReader = ChainReader(connection, expected_chain_id=chain.value)
            for symbol, units in metadata.deployment.items():
                for unit in units:
                    tornado: Tornado = Tornado(chain, symbol, unit, connection, reader=reader)
                    instances.append(tornado)
                    if not tornado.init(sync_only=True):
                        log.error(tag, f'Failed to initialize {chain_to_string(chain)}@{unit.value}{symbol.value.upper()}')
                        return
        _sync_pools(instances, keep)
    except KeyboardInterrupt:
        log.warn(tag, 'Interrupted')
    finally:
        for tornado in instances:
            tornado.un_init()
        for connection in connections.values():
            connection.stop()


def _save_deposit_note(tornado: Tornado, note: Note, index: int | None = None) -> str | None:
    suffix: str = f'_{index}' if index is not None else ''
    filename: str = f'{datetime.now().strftime("%Y-%m-%d_%H.%M.%S.%f")[:-3]}_{chain_to_string(tornado.chain)}_{tornado.symbol.value}_{tornado.unit.value}{suffix}.txt'
    backup_path: str = os.path.abspath(os.path.join(config.BACKUP_DIR, filename)).replace('\\', '/')
    backup_str        : str = Note.to_text(tornado.chain, tornado.symbol, tornado.unit, note)
    invoice_str       : str = Note.to_invoice(tornado.chain, tornado.symbol, tornado.unit, note)
    nullifier_hash_str: str = f'{chain_to_string(tornado.chain)}-{tornado.symbol.value}-{tornado.unit.value}-{note.nullifier_hash.hex().zfill(64)}'
    try:
        if not os.path.exists(config.BACKUP_DIR):
            os.makedirs(config.BACKUP_DIR, exist_ok=True)
        with open(backup_path, 'w') as f:
            f.write(f'Note: {backup_str}\n')
            f.write(f'Invoice: {invoice_str}\n')
            f.write(f'NullifierHash: {nullifier_hash_str}\n')
    except Exception as e:
        log.error(tag, f'Failed to save note to file: {e}')
        return None
    log.info(tag, f'IMPORTANT: Please save the note text below and keep it private', log.Color.YELLOW, log.Style.BOLD)
    log.info(tag, f'IMPORTANT: {backup_str}', log.Color.YELLOW, log.Style.BOLD)
    return backup_path


def _deposit(key: Key, tornado: Tornado, invoice: HexBytes | None = None) -> HexBytes | None:
    log.info(tag, f'Depositing {helper_func.upper_first_char(chain_to_string(tornado.chain))} {tornado.unit.value} {tornado.symbol.value.upper()}')
    note: Note | None = Note.create() if invoice is None else None
    commitment: HexBytes = note.commitment if note is not None else invoice
    backup_path: str | None = _save_deposit_note(tornado, note) if note is not None else None
    if note is not None and backup_path is None:
        return None
    tx_hash: HexBytes | None = tornado.deposit(commitment, key)
    if note is not None:
        if tx_hash is None:  # Transaction failed, remove the backup file
            try:
                os.remove(backup_path)
            except Exception as e:
                log.error(tag, f'Failed to remove failed deposit\'s backup file: {e}')
        else:  # Transaction succeeded, print the backup file path
            log.info(tag, f'IMPORTANT: Note backup saved to {backup_path}', log.Color.YELLOW, log.Style.BOLD)
    return tx_hash


def _wait_batch_receipt(connection: rpc.Interface, tx_hash: HexBytes, operation: str,
                        recipient: ChecksumAddress | None = None, *, timeout: int | None = None) -> TxReceipt | None:
    deadline = monotonic() + timeout if timeout is not None else None
    log.info(tag, f'Wait 15 seconds for {operation.lower()} transaction to be mined ...')
    delay = 15
    while True:
        if deadline is not None:
            delay = min(delay, deadline - monotonic())
            if delay <= 0:
                break
        helper_func.wait(Second(delay))
        if deadline is not None and monotonic() >= deadline:
            break
        receipt: TxReceipt | rpc.Error = connection.transaction_receipt(tx_hash)
        if rpc.is_error(receipt):
            log.warn(tag, f'Wait 5 seconds for {operation.lower()} transaction to be mined, RPC error: {receipt.code.value}')
        elif receipt is not None and receipt['blockNumber'] is not None:
            if receipt['status'] != 1:
                log.error(tag, f'{operation} transaction failed, tx_hash: {tx_hash.to_0x_hex()}')
                return None
            destination: str = f', recipient: {recipient}' if recipient else ''
            log.info(tag, f'{operation} transaction mined in block {receipt["blockNumber"]}, '
                          f'tx_hash: {tx_hash.to_0x_hex()}{destination}', log.Color.CYAN, log.Style.BOLD)
            return receipt
        else:
            log.info(tag, f'Wait 5 seconds for {operation.lower()} transaction to be mined ...')
        delay = 5
    log.error(tag, f'Timed out waiting for {operation.lower()} transaction receipt, tx_hash: {tx_hash.to_0x_hex()}. '
                   'Check the transaction before retrying.')
    return None


def _approve_batch(deposits: list[tuple[Tornado, HexBytes]], key: Key,
                   symbols: list[Symbol], depositor: ChecksumAddress) -> bool:
    first  : Tornado         = deposits[0][0]
    account: ChecksumAddress = key.eth_address()
    for symbol in symbols:
        transaction = batch_tx.approve_tx(deposits, account, symbol, depositor=depositor)
        tx_hash: HexBytes | None = batch_tx.send(first, transaction, key)
        if tx_hash is None or not _wait_batch_receipt(first.connection, tx_hash, 'Approval', timeout=BATCH_RECEIPT_TIMEOUT):
            return False
    return True


def deposit(key: Key, chain: ChainID, symbol: Symbol, unit: TornadoUnit, invoice: HexBytes | None = None) -> None:
    tornado: Tornado = Tornado(chain, symbol, unit)
    if not tornado.init(sync_only=True):
        return
    try:
        _deposit(key, tornado, invoice)
    except KeyboardInterrupt:
        log.warn(tag, 'Interrupted')
    tornado.un_init()


''' Example of batch
"{
    'ethereum': {
        'eth': {
            '10': 100,
            '100': 20
        }
    },
    'polygon': {
        'pol': {
            '100000': 1000
        }
    }
}"
'''
def deposit_batch(key: Key, batch: str) -> None:
    # Evaluate the batch string to a dictionary
    parsed: dict[ChainID, dict[Symbol, dict[TornadoUnit, int]]] = {}
    try:
        loaded: dict[str, dict] = eval(batch)
        for chain_str, v0 in loaded.items():
            chain: ChainID = string_to_chain(chain_str)
            if chain in parsed:
                log.error(tag, f'Duplicated key "{chain_str}" in the batch')
                return None
            parsed[chain] = {}
            for symbol_str, v1 in v0.items():
                symbol: Symbol = Symbol(symbol_str.lower())
                if symbol in parsed[chain]:
                    log.error(tag, f'Duplicated key "{symbol_str}" in the batch')
                    return None
                parsed[chain][symbol] = {}
                for unit_str, count in v1.items():
                    unit: TornadoUnit = TornadoUnit(unit_str)
                    if unit in parsed[chain][symbol]:
                        log.error(tag, f'Duplicated key "{unit_str}" in the batch')
                        return None
                    parsed[chain][symbol][unit] = int(count)
    except Exception as e:
        stack: str = traceback.format_exc()
        text: str = str(e)
        lines: list[str] = [f'deposit_batch() raised {type(e)} exception: {text}']
        lines.extend(stack.split('\n'))
        log.error(tag, lines)
        return None
    # Create and start RPC connections
    connections: dict[ChainID, rpc.Interface] = {}
    for chain in parsed.keys():
        if chain not in config.RPC_URLS:
            log.error(tag, f'No RPC URL configured for chain: {chain_to_string(chain)}')
            return None
        connections[chain] = rpc.Connection(chain, config.RPC_URLS[chain])
        if not connections[chain].start():
            log.error(tag, f'Failed to connect to RPC for {chain_to_string(chain)}')
            return None
    # One deposit transaction per chain
    try:
        for chain, v0 in parsed.items():
            instances: list[Tornado] = []
            deposits: list[tuple[Tornado, HexBytes]] = []
            backups: list[str] = []
            try:
                for symbol, v1 in v0.items():
                    for unit, count in v1.items():
                        tornado: Tornado = Tornado(chain, symbol, unit, connections[chain])
                        instances.append(tornado)
                        if not tornado.init(sync_only=True):
                            return
                        for _ in range(count):
                            log.info(tag, f'Depositing {helper_func.upper_first_char(chain_to_string(chain))} {unit.value} {symbol.value.upper()}')
                            note: Note = Note.create()
                            backup_path: str | None = _save_deposit_note(tornado, note, len(deposits) + 1)
                            if backup_path is None:
                                return
                            backups.append(backup_path)
                            deposits.append((tornado, note.commitment))
                if not deposits:
                    continue
                account  : ChecksumAddress        = key.eth_address()
                symbols  : list[Symbol]           = list(batch_tx.token_amounts(deposits))
                depositor: ChecksumAddress | None = None
                if symbols:
                    transaction = batch_tx.deploy_tx(deposits, account)
                    tx_hash: HexBytes | None = batch_tx.send(deposits[0][0], transaction, key)
                    if tx_hash is None:
                        return
                    receipt = _wait_batch_receipt(connections[chain], tx_hash, 'Deployment', timeout=BATCH_RECEIPT_TIMEOUT)
                    if receipt is None:
                        return
                    if not Web3.is_address(receipt.get('contractAddress')):
                        log.error(tag, f'Missing batch contract address in deployment receipt, tx_hash: {tx_hash.to_0x_hex()}')
                        return
                    depositor = Web3.to_checksum_address(receipt['contractAddress'])
                    log.info(tag, f'Batch deposit contract deployed at {depositor}', log.Color.CYAN, log.Style.BOLD)
                    if not _approve_batch(deposits, key, symbols, depositor):
                        return
                transaction = batch_tx.deposit_tx(deposits, account, depositor=depositor)
                tx_hash: HexBytes | None = batch_tx.send(deposits[0][0], transaction, key)
                if tx_hash is None:
                    return
                for backup_path in backups:
                    log.info(tag, f'IMPORTANT: Note backup saved to {backup_path}', log.Color.YELLOW, log.Style.BOLD)
                timeout = BATCH_RECEIPT_TIMEOUT if depositor is not None else None
                if not _wait_batch_receipt(connections[chain], tx_hash, 'Deposit', timeout=timeout):
                    return
            finally:
                for tornado in instances:
                    tornado.un_init()
    except KeyboardInterrupt:
        log.warn(tag, 'Interrupted')
    except (ValueError, RuntimeError) as e:
        log.error(tag, f'deposit_batch() failed: {e}')
    finally:
        for conn in connections.values():
            conn.stop()


def withdraw(note_text: str, recipient: ChecksumAddress, key_or_relayer: Key | str) -> None:
    parsed: tuple[ChainID, Symbol, TornadoUnit, Note] | None = Note.from_text(note_text)
    if parsed is None:
        log.error(tag, f'Failed to parse note: "{note_text}"')
        return
    chain, symbol, unit, note = parsed
    tornado: Tornado = Tornado(chain, symbol, unit)
    if not tornado.init(sync_only=False):
        return
    try:
        if _sync_pools([tornado]):
            tornado.withdraw(note, recipient, key_or_relayer)
    except KeyboardInterrupt:
        log.warn(tag, 'Interrupted')
    finally:
        tornado.un_init()


def withdraw_batch(notes_text: str, recipient: ChecksumAddress, key_or_relayer: Key | str) -> None:
    # Parse notes
    texts: list[str] = [n.strip() for n in notes_text.split(',')]
    parsed: dict[ChainID, dict[Symbol, dict[TornadoUnit, list[Note]]]] = {}
    for text in texts:
        p: tuple[ChainID, Symbol, TornadoUnit, Note] | None = Note.from_text(text)
        if p is None:
            log.error(tag, f'Failed to parse note: "{text}"')
            return
        chain, symbol, unit, note = p
        if chain not in parsed:
            parsed[chain] = {}
        if symbol not in parsed[chain]:
            parsed[chain][symbol] = {}
        if unit not in parsed[chain][symbol]:
            parsed[chain][symbol][unit] = []
        parsed[chain][symbol][unit].append(note)
    connections: dict[ChainID, rpc.Interface] = {}
    try:
        for chain in parsed:
            if chain not in config.RPC_URLS:
                log.error(tag, f'No RPC URL configured for chain: {chain_to_string(chain)}')
                return
            connection: rpc.Interface = rpc.Connection(chain, config.RPC_URLS[chain])
            connections[chain] = connection
            if not connection.start():
                log.error(tag, f'Failed to connect to RPC for {chain_to_string(chain)}')
                return

        for chain, symbols in parsed.items():
            connection = connections[chain]
            reader   : ChainReader                      = ChainReader(connection, expected_chain_id=chain.value)
            instances: list[Tornado]                    = []
            groups   : list[tuple[Tornado, list[Note]]] = []
            try:
                for symbol, units in symbols.items():
                    for unit, notes in units.items():
                        tornado: Tornado = Tornado(chain, symbol, unit, connection, reader=reader)
                        instances.append(tornado)
                        if not tornado.init(sync_only=False):
                            if isinstance(key_or_relayer, Key):
                                return
                            continue
                        groups.append((tornado, notes))
                if not groups:
                    continue
                pools: list[Tornado] = [tornado for tornado, _ in groups]
                if isinstance(key_or_relayer, Key):
                    if not _sync_pools(pools):
                        return
                    withdrawals: list[tuple[Tornado, Note]]  = [(tornado, note) for tornado, notes in groups for note in notes]
                    transaction: TxParams | rpc.Error | None = batch_tx.withdraw_tx(withdrawals, key_or_relayer.eth_address(), recipient)
                    tx_hash    : HexBytes | None             = batch_tx.send(withdrawals[0][0], transaction, key_or_relayer)
                    if tx_hash is None or not _wait_batch_receipt(connection, tx_hash, 'Withdraw', recipient):
                        return
                else:
                    with _running_sync(pools) as finish:
                        if finish is None:
                            return
                        for tornado, notes in groups:
                            if not finish(tornado):
                                return
                            for note in notes:
                                tx_hash = tornado.withdraw(note, recipient, key_or_relayer)
                                if tx_hash is not None:
                                    _wait_batch_receipt(connection, tx_hash, 'Withdraw', recipient)
            finally:
                for tornado in instances:
                    tornado.un_init()
    except KeyboardInterrupt:
        log.warn(tag, 'Interrupted')
    except ValueError as error:
        log.error(tag, f'withdraw_batch() failed: {error}')
    finally:
        for connection in connections.values():
            connection.stop()


def create_note(chain: ChainID, symbol: Symbol, unit: TornadoUnit) -> None:
    note              : Note = Note.create()
    backup_str        : str  = Note.to_text(chain, symbol, unit, note)
    invoice_str       : str  = Note.to_invoice(chain, symbol, unit, note)
    nullifier_hash_str: str  = f'{chain_to_string(chain)}-{symbol.value}-{unit.value}-{note.nullifier_hash.hex().zfill(64)}'
    # Save backup
    filename   : str = f'{datetime.now().strftime("%Y-%m-%d_%H.%M.%S.%f")[:-3]}_{chain_to_string(chain)}_{symbol.value}_{unit.value}.txt'
    backup_path: str = os.path.abspath(os.path.join(config.BACKUP_DIR, filename)).replace('\\', '/')
    try:
        if not os.path.exists(config.BACKUP_DIR):
            os.makedirs(config.BACKUP_DIR, exist_ok=True)
        with open(backup_path, 'w') as f:
            f.write(f'Note: {backup_str}\n')
            f.write(f'Invoice: {invoice_str}\n')
            f.write(f'NullifierHash: {nullifier_hash_str}\n')
    except Exception as e:
        log.error(tag, f'Failed to save note to file: {e}')
        return None
    # Print QR code in console
    qr = qrcode.QRCode(
        version=None,  # Select the best version automatically based on data length
        error_correction=qrcode.constants.ERROR_CORRECT_M,
        box_size=32,
        border=1,
    )
    qr.add_data(invoice_str)
    qr.make(fit=True)
    qr.print_ascii()
    # Print note text and invoice
    log.info(tag, f'Scan the QR code to transfer the invoice to online machine', log.Color.YELLOW, log.Style.BOLD)
    log.info(tag, f'IMPORTANT: Please save the note text below and keep it private', log.Color.YELLOW, log.Style.BOLD)
    log.info(tag, f'Note         : {backup_str}', log.Color.YELLOW, log.Style.BOLD)
    log.info(tag, f'Invoice      : {invoice_str}', log.Color.YELLOW, log.Style.BOLD)
    log.info(tag, f'NullifierHash: {nullifier_hash_str}', log.Color.YELLOW, log.Style.BOLD)
    log.info(tag, f'IMPORTANT: Note backup saved to {backup_path}', log.Color.YELLOW, log.Style.BOLD)


def _format_input_abbrev(text: str) -> str:
    """Format input text with abbreviated hex: <chain>-<symbol>-<unit>-<first8>...<last8>"""
    parts: list[str] = text.split('-')
    if len(parts) >= 4:
        chain_str, symbol_str, unit_str = parts[0], parts[1], parts[2]
        hex_part: str = '-'.join(parts[3:])  # Handle case where hex might contain '-'
        if len(hex_part) > 16:
            hex_abbrev: str = f'{hex_part[:8]}...{hex_part[-8:]}'
        else:
            hex_abbrev: str = hex_part
        return f'{chain_str}-{symbol_str}-{unit_str}-{hex_abbrev}'
    return text


def note_deposited(note_or_invoice: str) -> None:
    # Split input by comma and strip whitespace
    texts: list[str] = [t.strip() for t in note_or_invoice.split(',')]
    # Parse and group by (chain, symbol, unit), store (commitment, original_text) tuples
    grouped: dict[tuple[ChainID, Symbol, TornadoUnit], list[tuple[HexBytes, str]]] = {}
    for text in texts:
        parsed: tuple[ChainID, Symbol, TornadoUnit, Note] | tuple[ChainID, Symbol, TornadoUnit, HexBytes] | None = Note.from_text(text)
        if parsed is None:
            parsed = Note.from_invoice(text)
            if parsed is None:
                log.error(tag, f'Failed to parse note: "{text}"')
                continue
        chain, symbol, unit, note_or_commitment = parsed
        if isinstance(note_or_commitment, Note):
            commitment: HexBytes = note_or_commitment.commitment
        else:
            commitment: HexBytes = note_or_commitment
        key = (chain, symbol, unit)
        if key not in grouped:
            grouped[key] = []
        grouped[key].append((commitment, text))
    # Process each group
    for (chain, symbol, unit), items in grouped.items():
        tornado: Tornado = Tornado(chain, symbol, unit)
        for commitment, original_text in items:
            deposited: bool | None = tornado.note_deposited(commitment)
            if deposited is not None:
                log.info(tag, f'{str(deposited)}: {_format_input_abbrev(original_text)}')


def note_withdrawn(note_text_or_nullifier_hash: str) -> None:
    # Split input by comma and strip whitespace
    texts: list[str] = [t.strip() for t in note_text_or_nullifier_hash.split(',')]
    # Parse and group by (chain, symbol, unit), store (nullifier_hash, original_text) tuples
    grouped: dict[tuple[ChainID, Symbol, TornadoUnit], list[tuple[HexBytes, str]]] = {}
    for text in texts:
        parsed: tuple[ChainID, Symbol, TornadoUnit, Note] | tuple[ChainID, Symbol, TornadoUnit, HexBytes] | None = Note.from_text(text)
        if parsed is None:
            split: list[str] = text.split('-')
            if len(split) != 4:
                log.error(tag, f'Failed to parse note or nullifier_hash: "{text}", expecting format "chain-symbol-unit-<hex>"')
                continue
            chain_str , symbol_str , unit_str , nullifier_hash_str = split
            try:
                parsed = (
                    string_to_chain(chain_str),
                    Symbol(symbol_str.lower()),
                    TornadoUnit(unit_str),
                    HexBytes(nullifier_hash_str)
                )
            except:
                log.error(tag, f'Failed to parse note or nullifier_hash: "{text}"')
                continue
        chain, symbol, unit, note_or_nullifier_hash = parsed
        if isinstance(note_or_nullifier_hash, Note):
            nullifier_hash: HexBytes = note_or_nullifier_hash.nullifier_hash
        else:
            nullifier_hash: HexBytes = note_or_nullifier_hash
        key = (chain, symbol, unit)
        if key not in grouped:
            grouped[key] = []
        grouped[key].append((nullifier_hash, text))
    # Process each group
    for (chain, symbol, unit), items in grouped.items():
        tornado: Tornado = Tornado(chain, symbol, unit)
        for nullifier_hash, original_text in items:
            withdrawn: bool | None = tornado.note_withdrawn(nullifier_hash)
            if withdrawn is not None:
                log.info(tag, f'{str(withdrawn)}: {_format_input_abbrev(original_text)}')


